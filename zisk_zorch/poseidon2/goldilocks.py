# pil2's matmul_m4 in matrix form (HorizenLabs reference M4) — distinct from
# Plonky3's M4 that zorch defaults to.
_M4 = [[5, 7, 1, 3], [4, 6, 1, 1], [1, 3, 5, 7], [1, 1, 4, 6]]


def _external_matrix(width: int) -> Array:
    """pil2 `matmul_external` as a matrix: per-4-block M4, then each block adds
    the M4-image column sums of all blocks — (I + J_blocks) ⊗ M4, i.e. 2x M4 on
    the diagonal blocks and M4 elsewhere. Width 4 is plain M4."""
    m = [
        [_M4[i % 4][j % 4] * (2 if i // 4 == j // 4 else 1) for j in range(width)]
        for i in range(width)
    ]
    return _u64_array(m) if width > 4 else _u64_array(_M4)


