"""Poseidon2-Goldilocks parameters — the pil2-stark hash family ZisK proves with.

Round constants, internal diagonals, and round counts for the two sponge widths
ZisK reaches — 16 and 4 — transcribed from pil2-proofman v1.0.0-alpha's `fields`
crate:
https://github.com/0xPolygonHermez/pil2-proofman/blob/v1.0.0-alpha/fields/src/poseidon2_constants.rs
(regenerable: golden/ pins the same crate, and goldilocks_test.py byte-matches
every width against vectors generated by that crate).

Widths 8 and 12 are not here: they are the node widths of merkle arity 2 and 3,
and `starkStruct.merkleTreeArity` is a single per-key value — governing the
stage, constant and FRI trees alike — that ZisK fixes at 4.

The pil2 conventions these parameters encode on top of zorch's agnostic core:

- Capacity is always 4 (`CAPACITY`); the rate is width - 4 except width 4,
  whose rate pil2 fixes at 4 (the full state — used only as a compression
  primitive, never a sponge). Width 4 survives the arity narrowing because it
  is not an arity at all: it is the permutation behind pil2's grinding
  predicate.
- The external matrix is NOT zorch's default: pil2's `matmul_m4` implements
  the HorizenLabs-reference M4 ([[5,7,1,3],[4,6,1,1],[1,3,5,7],[1,1,4,6]]),
  not Plonky3's [[2,3,1,1],...] that `default_external_matrix` builds. The
  block form is the same (2x M4 on the diagonal 4-blocks, M4 off-diagonal;
  plain M4 at width 4), so the full matrix is passed explicitly per width.
  zorch#264 carries the base M4 as an `external_m4` marker attribute, which the
  compiler applies via multiply-free add-chains, so the block-structured width
  16 lowers to the dedicated `zorch.poseidon2` emitter — the fast
  commit-compile path. Width 4's plain single-block M4 is
  not marker-carried, so it stays on the generic fused region.
- The internal layer is `Diag(d) + J` (pil2's `prodadd`: out_i = d_i*x_i +
  sum), i.e. zorch's `internal_diag = d`, `internal_j_scale = 1`.
"""

